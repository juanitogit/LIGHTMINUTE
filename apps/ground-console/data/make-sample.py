#!/usr/bin/env python3
"""Build the ground-console fixture from the engine export (SYNTHETIC).

    python apps/ground-console/data/make-sample.py

Copies only the fields the console renders, straight out of
`apps/crew-tablet/public/demo-data.json` (owner A1). No number is recomputed
or rounded differently. The `.js` twin exists because `file://` cannot
`fetch()` local JSON; it just assigns the same object to a global.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SRC = ROOT / "apps" / "crew-tablet" / "public" / "demo-data.json"

KEEP_INDICATOR = ("value", "baseline", "ci95", "z", "n_seen", "unit", "lens", "hrp_risk", "hazard")
KEEP_CREW = ("level", "syndrome_z", "learning", "card", "card_source", "routing")


def main() -> None:
    doc = json.loads(SRC.read_text(encoding="utf-8"))
    days = []
    for day in doc["days"]:
        crew = {}
        for crew_id, entry in (day.get("crew") or {}).items():
            slim = {key: entry[key] for key in KEEP_CREW if key in entry}
            slim["indicators"] = {
                name: {key: spec[key] for key in KEEP_INDICATOR if key in spec}
                for name, spec in (entry.get("indicators") or {}).items()
            }
            crew[crew_id] = slim
        days.append({"day": day["day"], "crew": crew, "attribution": day.get("attribution")})

    fixture = {
        "synthetic": True,
        "note": "Synthetic fixture copied from apps/crew-tablet/public/demo-data.json. Not a medical device.",
        "indicators": doc.get("indicators", []),
        "days": days,
    }
    compact = json.dumps(fixture, separators=(",", ":"), ensure_ascii=False)
    (HERE / "sample-scenario.json").write_text(compact, encoding="utf-8")
    (HERE / "sample-scenario.js").write_text(
        "/* generated by make-sample.py - do not edit. Synthetic fixture for file:// */\n"
        f"globalThis.__LIGHTMINUTE_SAMPLE__ = {compact};\n",
        encoding="utf-8",
    )
    print(f"wrote {HERE / 'sample-scenario.json'} ({len(compact) / 1024:.0f} KB, {len(days)} days)")


if __name__ == "__main__":
    main()
